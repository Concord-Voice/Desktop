import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const dsn = process.env.SENTRY_DSN_DESKTOP ?? '';
const isProduction = process.env.NODE_ENV === 'production';

if (isProduction && !dsn) {
  console.warn(
    '\n  ⚠ [generate-sentry-config] NODE_ENV=production but SENTRY_DSN_DESKTOP is unset.\n' +
      '    The built binary will have Sentry DISABLED.\n' +
      '    This is likely a build configuration error.\n'
  );
}

const content = `// AUTO-GENERATED FILE — DO NOT EDIT BY HAND
// Generated by client/desktop/scripts/generate-sentry-config.ts at build time.
// To change the value, set the SENTRY_DSN_DESKTOP environment variable before building.
// This file is gitignored.

export const SENTRY_DSN: string = ${JSON.stringify(dsn)};
`;

const outputPath = resolve(__dirname, '../src/shared/sentry-config.generated.ts');
try {
  writeFileSync(outputPath, content);
  console.log(`[generate-sentry-config] Wrote ${outputPath} (DSN: ${dsn ? 'set' : 'empty'})`);
} catch (err) {
  console.error(
    `[generate-sentry-config] FATAL: Failed to write ${outputPath}.\n` +
      `  Ensure the parent directory exists and is writable.\n` +
      `  Error: ${err instanceof Error ? err.message : String(err)}`
  );
  process.exit(1);
}
